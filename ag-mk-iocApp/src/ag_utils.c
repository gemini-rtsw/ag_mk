/*+
 *   Function name:
 *   agAb2xy
 *
 *   Purpose:
 *   Convert rotary table and probe arm angles into x and y coordinates
 *   in the focal plane. 
 *
 *   Description:
 *   The A&G probe arms are mounted on a rotary table whose orientation is
 *   specified by an angle alpha. The probe arm then moves in an arc whose
 *   pivot is fixed to this table. The angle of the arm is specified by
 *   beta. By changing the angles alpha and beta the probe pick off 
 *   mirror can be positioned at any x and y in the focal plane. The 
 *   situation is complicated by the fact that the pivots of the arms are
 *   tilted so that the pickoff mirror always points at the image of M1
 *   in M2 and that the x, y frame of the A&G is rotated relative to that
 *   of the telescope. This routine takes in angles alpha and beta and
 *   generates the corresponding TCS x and y focal plane coordinates.
 *   This routine replaced the routine alphabeta_2_xy in the original
 *   A&G software which relied on corrections generated by the TCS and
 *   retains some of its structure.
 *
 *   Invocation:
 *   status = agAb2xy(mechindex, alpha, beta, CalParm, RTPA_Orient, &x, &y)
 *
 *   Parameters: (">" input, "!" modified, "<" output)  
 *      (>) mechindex      (long)   Index of mechanism i.e. which probe
 *      (>) alpha          (double) Rotary table angle (degs)
 *      (>) beta           (double) Probe arm angle (degs)
 *      (>) CalParm[7]     (double) Array of probe calibration parameters
 *      (!) RTPA_Orient[2] (int)    Array of orientation flags
 *      (<) x              (double) TCS focal plane coord (mm)
 *      (<) y              (double) TCS focal plane coord (mm)
 *
 *   Function value:
 *   (<)  status  (long)  Return status, 0 = OK
 * 
 *-
 */

#define RADIUS_RT	CalParm[0]
#define X_OFFSET	CalParm[1]
#define Y_OFFSET	CalParm[2]
#define X_SCALE		CalParm[3]
#define Y_SCALE		CalParm[4]
#define ARM_LENGTH      CalParm[6]

#define RT_ORIENT	RTPA_Orient[0]
#define PA_ORIENT	RTPA_Orient[1]

long agAb2xy(long mechindex, double alpha_rot, double beta_arm,
             double CalParm[7], int RTPA_Orient[2],
             double* x, double* y )
{
  double xp, yp ;                        /* xp, yp in rotated frame 	*/
  double a ;                             /* table angle (rads)          */
  double b ;                             /* arm angle (rads)            */
  double hp ;                            /* probe height (mm)           */
  double d ;                             /* M1 image to focal plane     */

  /* Initialize a couple of variables to remove warnings */
  xp = yp = 0;

  /* calculation Orient re-inserted ocf 26.1.200 */
  RT_ORIENT = (alpha_rot < 0) ?	CW : CCW;	/* CW means: Angle < 0	*/	
  PA_ORIENT = (beta_arm  < 0) ?	CW : CCW;	

  a = alpha_rot * DD2R ;
  b = beta_arm * DD2R ;
  d = M1TOFPLANE ;
  if (mechindex == p1_probe)
    hp = P1TOFPLANE ;
  else
    hp = P2TOFPLANE ;

  gemAb2xy (a, b, d, hp, RADIUS_RT, ARM_LENGTH, &xp, &yp) ;

  *x = (xp - X_OFFSET) / X_SCALE;
  *y = (yp - Y_OFFSET) / Y_SCALE;

  return (0);
}

/*+
 *   Function name:
 *   agXy2ab
 *
 *   Purpose:
 *   Convert TCS focal plane x, y to rotary table and probe arm angles
 *
 *   Description:
 *   This routine is the inverse of agAb2xy. It takes TCS focal plane 
 *   coordinates and converts them into rotary table and probe arm angles
 *   such that the centre of the pick off mirror is positioned at the
 *   specified x, y. The routine takes into account the user's preference
 *   for orientation and whether the rotary table demand falls in the 
 *   overlap region. Within these constraints the demand that minimises the
 *   rotary table movement is chosen.
 *   
 *   Not taking into account the flag new_track_id.
 *
 *   Invocation:
 *   status = agXy2ab(mechindex, new_track_id, x, y, CalParm[7], Limits[6], RTPA_Orient[2],
 *                    CurrRTAngle, &alpha, &beta)
 *
 *   Parameters: (">" input, "!" modified, "<" output)  
 *      (>) mechindex      (long)     Mechanism index
 *      (>) new_track_id   (long)     New Track ID flag.
 *      (>) x              (double)   TCS focal plane coord (mm)
 *      (>) y              (double)   TCS focal plane coord (mm)
 *      (>) CalParm[7]     (double)   Probe calibration parameters
 *      (>) Limits[6]      (double)   Probe mechanism limits
 *      (>) RTPA_Orient[2] (int)      Probe orientation flags
 *      (>) CurrRtAngle    (double)   Current table angle (degs)
 *      (<) alpha          (double *) Demand rotary table angle (degs)
 *      (<) beta           (double *) Demand probe arm angle (degs)
 *
 *   Function value:
 *   (<)  status  (long)  Return status, 0 = OK
 * 
 *-
 */

#define MIN_RADIUS      0.01

long agXy2ab (long mechindex, long new_track_id, double xtr, double ytr, double CalParm[7],
		double Limits[6], int RTPA_Orient[2], double CurrRTAngle,
                double* alpha_rot, double *beta_arm)
{

  double x, y;			/* x, y after translation		*/
  double radius, alpha, alpha1; /* polar coord, ref=centre, alpha=rad	*/
  double gamma1, gamma;		/* triangle calcs.			*/
  double alpha_rotCW;        	/* CW  table solution (degs)          	*/
  double alpha_rotCCW;      	/* CCW table solution (degs)            */
  double dist2;              	/* RT-Distance to go  (degs)           	*/
  double dr;                 	/* Magnitude of radius difference       */
  double rlimit;            	/* Minimum radius to look for a solution*/
  double distCW;             	/* RT-Distance to go for  CW solution 	*/
  double distCCW;           	/* RT-Distance to go for CCW solution	*/
  double hp ;                   /* height of probe above focal plane    */
  double d ;                    /* M1 image to focal plane (mm)         */

  /* Initialize a handful of variables to 0 to remove warnings. */
  alpha = alpha1 = gamma = gamma1 = 0;
  distCCW = 0;

  x = xtr * X_SCALE + X_OFFSET;		/* Translation of FOR	*/
  y = ytr * Y_SCALE + Y_OFFSET;		/* (Frame of reference)	*/

  radius = sqrt(x*x+y*y);

/* Check for demands too large or too small. 	
*  Limit the demand  radius to RADIUS_RT.
*
*  RADIUS_RT is just the radius of the mounting point of the probe arm; 
*  it's not the physically allowable maximum radius at the PA limit switch.
*  It may be allowable to drive outside RADIUS_RT since this may or may not
*   be within the limits.
*/
/*
  if (radius > RADIUS_RT) 
  {
    x *= RADIUS_RT / radius ;
    y *= RADIUS_RT / radius ;
    radius = RADIUS_RT ;
  }
*/
/* Set up a minimum radius depending on situation with regard to difference
*  in radius of the rotary table and probe arm
*/
  dr = ARM_LENGTH - RADIUS_RT ;
  if (dr  < 0.0)  		dr = -dr ;
  if (dr  <= MIN_RADIUS)  	rlimit = MIN_RADIUS ;
  else				rlimit = dr ;

/* Solve for rotary table and probe arm angles for the given x,y */

  if (radius <= rlimit ) {

/* There is no solution in this case so drive as close as possible to the 
*  centre, leaving rotary table where it is
*/ 
    *beta_arm   = 0.0 ;
    *alpha_rot  = CurrRTAngle * DD2R ;

  } else {


    d = M1TOFPLANE ;
    if (mechindex == p1_probe)
      hp = P1TOFPLANE ;
    else
      hp = P2TOFPLANE ;

    gemXy2ab (x, y, d, hp, RADIUS_RT, ARM_LENGTH, &alpha, &gamma, &alpha1,
              &gamma1) ;

/* In calculating the demand angles, take into account users preference for the 
*  orientation and whether the rotary table demand falls in the overlap region. 
*  Within these constraints choose the demand that minimises the amount that 
*  the rotary table must be moved.
*/
    alpha_rotCCW = alpha * DR2D ;
    if (alpha_rotCCW >  180.0)  alpha_rotCCW -= 360.0 ;
    if (alpha_rotCCW < -180.0)  alpha_rotCCW += 360.0 ;

    if (PA_ORIENT != CW) 
    {
      distCCW  = CurrRTAngle - alpha_rotCCW ;
      if (distCCW < 0.0) distCCW = -distCCW ;

      if (alpha_rotCCW <= 180.0 && alpha_rotCCW > 360.0 + Limits[1]) 
      {
        dist2 = CurrRTAngle - (alpha_rotCCW - 360.0) ;
        if (dist2 < 0.0) dist2 = -dist2 ;
        if (dist2 < distCCW) 
        {
          distCCW 	= dist2 ;
          alpha_rotCCW -= 360.0 ;
        }
      } 
      else 
      if (alpha_rotCCW > -180.0 && alpha_rotCCW < Limits[0] - 360.0) 
      {
        dist2 = CurrRTAngle - (alpha_rotCCW + 360.0) ;
        if (dist2 < 0.0)  dist2 = -dist2 ;
        if (dist2 < distCCW) 
        {
          distCCW 	= dist2 ;
          alpha_rotCCW += 360.0 ;
        }
      }				
    }				/* PA_Orient == CCW || CWCCW	*/

    alpha_rotCW = alpha1 * DR2D ;
    if (alpha_rotCW >  180.0)  alpha_rotCW -= 360.0 ;
    if (alpha_rotCW < -180.0)  alpha_rotCW += 360.0 ;

    if (PA_ORIENT != CCW) 
    {
      distCW = CurrRTAngle - alpha_rotCW ;
      if (distCW < 0.0) distCW = -distCW ;

      if (alpha_rotCW <= 180.0 && alpha_rotCW > 360.0 + Limits[1]) 
      {
        dist2 = CurrRTAngle - (alpha_rotCW - 360.0) ;
        if (dist2 < 0.0) dist2 = -dist2 ;
        if (dist2 < distCW ) 
        {
          distCW = dist2 ;
          alpha_rotCW -= 360.0 ;
        }
      } 
      else  
      if (alpha_rotCW > -180.0 && alpha_rotCW < Limits[0] - 360.0) 
      {
        dist2 = CurrRTAngle - (alpha_rotCW + 360.0) ;
        if (dist2 < 0.0)  dist2 = -dist2 ;
        if (dist2 < distCW) 
        {
          distCW       = dist2 ;
          alpha_rotCW += 360.0 ;
        }
      }
    }				/* PA_ORIENT == CW || CWCCW	*/

/* Finally set the output demands now that all the options have been explored */
    if (PA_ORIENT  == CWCCW  ) 
    { if (distCW    < distCCW) 
      { *alpha_rot  = alpha_rotCW ;
        *beta_arm   = -gamma * DR2D ;
      } 
      else 
      { *alpha_rot  = alpha_rotCCW ;
        *beta_arm   = gamma * DR2D ;
      }
    }
    else
    { if (PA_ORIENT == CW ) 
      { *alpha_rot  = alpha_rotCW ;
        *beta_arm   = -gamma * DR2D ;
      } 
      else 
      { *alpha_rot  = alpha_rotCCW ;
        *beta_arm   = gamma * DR2D ;
      }
    }
  }			/* (radius > rlimit) 	*/

/* Check the user's preference for Orientation of RT if in overlap region	*/

  if (RT_ORIENT== CW && *alpha_rot >  360.0+Limits[1])  
    *alpha_rot -= 360.0;
  else if (RT_ORIENT==CCW && *alpha_rot < -360.0+Limits[0])  
    *alpha_rot += 360.0;

/* Limit the values to the allowed range such that 
*   no invalid demand beyond the limit switches 
*   can leave this routine.	
*/

  *alpha_rot = limit (*alpha_rot, Limits[1], Limits[0]); /* 1=neg.  0=pos. */
  *beta_arm  = limit (*beta_arm,  Limits[3], Limits[2]);

  return (0);
}


