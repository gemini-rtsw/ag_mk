long queryLUT (struct cadRecord  *pcad)
{
  extern struct rset lutoutRSET;	/* extern global var (recSup)	*/

  char messages[80];     		/* Message buffer */
  struct link    *plink;
  struct pv_link *ppv_link;
  struct dbAddr  *paddr;
  struct dbr_enumStrs es;
  int i;
  long returnval = CAD_REJECT;		/* = -1; */
  int mechindex = query_cadname(pcad->name);  


        /* test the inputs are in the LUT configuration */
        if (pcad->outa.type == DB_LINK)
        {
          plink    = (struct link *) &pcad->outa;
          ppv_link = &(plink->value.pv_link);
          paddr    = (struct dbAddr *)(ppv_link->pvt);

          (lutoutRSET.get_enum_strs)(paddr, &es);

          for (i = 0; i < es.no_str; i++)
              if (strncmp (pcad->a, es.strs[i], MAX_STRING_SIZE) == 0)
                  break;	/* stop for-loop */


          if (i < es.no_str)	/* name recognised */
		returnval = CAD_ACCEPT;	
	  else	returnval = CAD_REJECT;	
        }
	else
	{
	  sprintf( messages, "OUTA is not a DB_LINK to a LUT!"); 
	  strncpy( pcad->mess, messages, MAX_STRING_SIZE );
	  sprintf( messages, "\t%s\t- %s", pcad->name, pcad->mess);
	  agLogMessage( mechindex, DEB_ERROR,  messages);
	}
    return returnval;
}				/* queryLUT */

