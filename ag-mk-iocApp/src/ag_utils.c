/* getpos works only on non-switched channels!	*/

long getpos (int mechindex, double current[3], double target[3], double demand[3])
{
  int    card, motor;				/* PMAC-#, PMAC-ch.	*/
  long   lval1;					/* help variable	*/
  int	 ndim,i,k;

  ndim = limit (getdims (mechindex), 1, 3);
  k = (ndim==1) ? 0 : 1;

  for  (i=0; i<ndim; i++)				/* top, x, y, z	*/
  {
    motor=PlcNr[mechindex][i+k];   card=0;		/* PMAC1	*/
    if (motor>16) {motor=motor-16; card=1; }		/* PMAC2	*/

    if (getsimu(mechindex)==SIM_NONE)
      getDPvals(motor, card, &lval1, &(current[i]), &(demand[i]), &(target[i]));
    else  
      current[i] = demand[i] = target[i] = 0; /* sim: values from simulation! */

  }
  return (0);
}

