long tai2str (char* messages, double t)
{
  int date [7];

  timeThenC (t,TAI,3,date);		/* 3 dig in fract. (=ms)*/

  if (t<1e-3 || t>6e9) sprintf( messages, "%- 19.12g", t);
  else sprintf( messages, "%02d.%02d.%d %02d:%02d:%02d.%03d", 
    date[2], date[1], date[0], date[3], date[4], date[5], date[6]);

  return (0);
}

