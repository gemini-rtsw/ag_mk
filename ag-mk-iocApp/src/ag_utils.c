/*+
 *   Function name:
 *   doPLCcomm
 *
 *   Purpose:
 *   Sends a command plus parameters to a PMAC PLC program
 *
 *   Description:
 *   If the mechanism addressed is not in simulation mode then the demand
 *   positions are sent to the appropriate PMAC PLC programs followed by
 *   a command. In simulation mode the parameters are sent instead to the
 *   appropriate simulator.
 *
 *   Invocation:
 *   status = doPLCcomm (mech, command, &posn)
 *
 *   Parameters: (">" input, "!" modified, "<" output)  
 *      (>)   mech      (int)    Index to mechanism 
 *      (>)   command   (long)   Index to command
 *      (>)   posn      (long *) Demanded encoder psoition 
 *
 *   Function value:
 *   (<)  status  (long)  Return status, 0 = OK
 * 
 *-
 */

long doPLCcomm (int mechindex, long command, long *Pos)
{
  int card, motor;

/* Save the last command. This is needed in some cases so that special
*  demands can be sent through the PMAC mailboxes when a mechanism 
*  goes IDLE. These special demands depend on whether the command was
*  park, datum move etc.
*/
  lastPLCcomm[mechindex] = command ;

  if (getsimu(mechindex) == SIM_NONE) {

    motor = getplcn (mechindex, 0);
    card  = getcard (mechindex, 0);

    if (Pos != NULL) {
      putDPRamDP(PosStart + motor, Pos[0],  card, 0);	/* give Pos.	*/
      if ((motor = getplcn (mechindex, 1)) != 0 );	/* sub PLC prog */
        putDPRamDP(PosStart + motor, Pos[0], card, 0);	/* give Pos.	*/
      if ((motor = getplcn (mechindex, 2)) != 0 );	/* sub PLC prog */
        putDPRamDP(PosStart + motor, Pos[1], card, 0);	/* give Pos.	*/
      if ((motor = getplcn (mechindex, 3)) != 0 );	/* sub PLC prog */
        putDPRamDP(PosStart + motor, Pos[2], card, 0);	/* give Pos.	*/
    }

/* If we are going to command the Tilt mechanism of the science fold then
*  set the P term of the servo. Don't bother to do this if the command is
*  null i.e. set to 0. This is a waste of time but even more important
*  init_DPRam calls this function prior to the driver being properly
*  initialised and this causes the routine to hang.
*  This code is only needed currently for Gemini North, so uncomment the
*  following section before installing there.
*/

#ifdef NOTDEF
    if (command) {
      long terminator ;
      char response[MAX_STRING_SIZE];
      char errmsg[MAX_STRING_SIZE];

      if (mechindex == ag_sf || mechindex == ag_Tilt) {
       terminator = drvPmacMbxWriteRead (card, "#4K I430=4000", response, errmsg);
       if (errmsg[0]) {
         printf ("doPLCcomm: failed to set P term of SF tilt servo\n");
       }
      }
    }
#endif

    motor = getplcn (mechindex, 0);
    putDPRam  (FlagStart+motor, command, card, 0);	/* give Command	*/

    if (mechindex == hrwfs_cc || mechindex == ag_cc) {  /* special coding */
      card = 0;						/* PLC20/21, PM 1 */
      if (Pos != NULL)
        putDPRamDP(PosStart +motor, Pos[0],  card, 0);	/* give 1 Pos.	*/
      putDPRam    (FlagStart+motor, command, card, 0);	/* give Command	*/
    }

  } else {

/* In simulation mode we have to check each mechanism index to see if it
*  is actually a composite i.e. made up of sub mechanisms and then send
*  the command to each simulator.
*/
    if (mechindex == p1_probe) {
      agSimCommand(p1_probe, command, Pos[0]) ;
      agSimCommand(p1_RT4, command, Pos[0]) ;
      agSimCommand(p1_PA4, command, Pos[1]) ;
      agSimCommand(p1_focus, command, Pos[2]) ;
    } else if (mechindex == p2_probe) {
      agSimCommand(p2_probe, command, Pos[0]) ;
      agSimCommand(p2_RT3, command, Pos[0]) ;
      agSimCommand(p2_PA3, command, Pos[1]) ;
      agSimCommand(p2_focus, command, Pos[2]) ;
    } else if (mechindex == ag_sf) {
      agSimCommand(ag_sf, command, Pos[0]) ;
      agSimCommand(ag_RT2, command, Pos[0]) ;
      agSimCommand(ag_Tilt, command, Pos[1]) ;
      agSimCommand(ag_Lin2, command, Pos[2]) ;
    } else if (mechindex == ag_ao) {
      agSimCommand(ag_ao, command, Pos[0]) ;
      agSimCommand(p2_RT3, command, Pos[0]) ;
      agSimCommand(ag_PA3AO, command, Pos[1]) ;
    } else {
      agSimCommand(mechindex, command, Pos[0]) ;
    }

  }

  return (0);
 
}

