long setGIS(int mechindex, int value)
{
  char messages[80];		/* Message buffer */
  int i;
  long returnval = 0;

  if ((mechindex < MAX_INDEX) && 
     ((value==GIS_ON)||(value==GIS_OFF)))
    gis_events [mechindex] = value;
  else
  {
    sprintf( messages, "GIS - invalid request !"); 
    agLogMessage( mechindex, DEB_ERROR, messages);
    returnval = -1;
  }

  for (i=0; i < MAX_INDEX; i++)
    if (gis_events [i] == GIS_ON)  break;

  if (i < MAX_INDEX)	gis_event = GIS_ON;
  else			gis_event = GIS_OFF;

  return (returnval);
}
